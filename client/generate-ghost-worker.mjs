/* Generates client/src/ghost-worker-source.ts: the unridden-
   ghost worker (client/src/unridden-ghost-worker.ts), bundled
   on its own as one classic-script file and carried in the
   client bundle as a string, from which the app creates the
   worker through a Blob URL (see unridden-ghost-client.ts).

   Why not `new Worker(new URL("./unridden-ghost-worker.ts",
   import.meta.url))`: the canonical client build (Bun.build,
   owned by @hatch/space-sdk/build) passes that expression
   through verbatim and never emits the worker file — verified
   against Bun 1.4.4 — so the standard pattern would 404 in
   production. Bundling the worker here, as a pre-step of
   client/build.mjs, keeps the deployed worker exactly as
   fresh as the code it is built from.

   The generated file is also committed: the pipeline typechecks
   the client before it bundles, and the import in
   unridden-ghost-client.ts must resolve then. Regenerate the
   committed copy with `bun ./client/generate-ghost-worker.mjs`
   after touching the worker or anything it imports. */
import { writeFile } from "node:fs/promises";

export async function generateGhostWorkerSource() {
  const result = await Bun.build({
    entrypoints: ["./client/src/unridden-ghost-worker.ts"],
    target: "browser",
    format: "iife",
    minify: true,
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    throw new Error("generate-ghost-worker: worker bundle failed");
  }
  const source = await result.outputs[0].text();
  const generated =
    "/* GENERATED by client/generate-ghost-worker.mjs — do not edit.\n" +
    "   The bundled unridden-ghost worker, carried as a string so the\n" +
    "   app can create it from a Blob URL (the client bundler does not\n" +
    "   bundle Worker references). Regenerate with:\n" +
    "     bun ./client/generate-ghost-worker.mjs */\n" +
    `export const UNRIDDEN_GHOST_WORKER_SOURCE = ${JSON.stringify(source)};\n`;
  await writeFile("./client/src/ghost-worker-source.ts", generated);
  return generated;
}

if (import.meta.main) {
  await generateGhostWorkerSource();
  console.log("ghost-worker-source.ts regenerated");
}
